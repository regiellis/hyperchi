package content_test

import (
	"fmt"
	"testing/fstest"

	"github.com/regiellis/hyperchi/hyperchi/content"
)

func ExampleSchemaFor() {
	type Post struct {
		Title  string `json:"title" content:"required"`
		Author string `json:"author" content:"required,ref=authors"`
	}
	schema, err := content.SchemaFor[Post]("Post")
	if err != nil {
		panic(err)
	}
	layer := content.NewContentLayer(&content.ContentConfig{FS: fstest.MapFS{
		"posts/hello.md":  {Data: []byte("---\ntitle: Hello\nauthor: authors-regi\n---\nHello")},
		"authors/regi.md": {Data: []byte("---\nname: Regi\n---\nRegi")},
	}})
	layer.DefineCollection(content.CollectionConfig{Name: "posts", Schema: schema})
	if err := layer.LoadContent(); err != nil {
		panic(err)
	}
	snapshot := layer.GetAllCollections()
	posts, total, err := content.QueryTyped[Post](snapshot["posts"], content.ContentQuery{Limit: 10})
	if err != nil {
		panic(err)
	}
	fmt.Println(total, posts[0].Data.Title)
	targets, err := content.ResolveReferences(snapshot, snapshot["posts"].Contents[posts[0].ID], "author")
	if err != nil {
		panic(err)
	}
	fmt.Println(targets[0].GetString("name"))
	// Output:
	// 1 Hello
	// Regi
}

func ExampleGenerateTypes() {
	schema := content.NewSchema("Post").Field("title", content.FieldTypeString).Required().Build().Build()
	source, err := content.GenerateTypes("models", map[string]*content.ContentSchema{"Post": schema})
	if err != nil {
		panic(err)
	}
	fmt.Print(string(source))
	// Output:
	// // Code generated by hyperchi/content.GenerateTypes; DO NOT EDIT.
	//
	// package models
	//
	// // Post is front matter decoded with the Post schema.
	// type Post struct {
	// 	Title string "json:\"title\" content:\"required\""
	// }
}
