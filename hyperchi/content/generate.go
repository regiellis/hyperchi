package content

import (
	"bytes"
	"fmt"
	"go/format"
	"go/token"
	"strconv"
	"strings"
	"unicode"
)

// GenerateTypes emits deterministic, gofmt-formatted structs for schemas.
// Map keys are exported Go type names; fields are derived from front matter
// names with JSON and content tags. Scalar slices use ElementType (any if
// unset); reference slices always use string IDs. Types contain no runtime
// defaults, constraints, transforms, or validator functions: keep using the
// original schemas when loading content. Write the result from a go:generate
// program; this function performs no filesystem writes.
func GenerateTypes(packageName string, schemas map[string]*ContentSchema) ([]byte, error) {
	if !token.IsIdentifier(packageName) || packageName == "_" {
		return nil, fmt.Errorf("content: invalid package name %q", packageName)
	}
	var body bytes.Buffer
	usesTime := false
	for _, name := range sortedKeys(schemas) {
		if !token.IsIdentifier(name) || !token.IsExported(name) {
			return nil, fmt.Errorf("content: invalid exported type name %q", name)
		}
		schema := schemas[name]
		if schema == nil {
			return nil, fmt.Errorf("content: nil schema for %s", name)
		}
		required := map[string]bool{}
		for _, field := range schema.Required {
			if _, ok := schema.Fields[field]; !ok {
				return nil, fmt.Errorf("content: required field %q not defined in %s", field, name)
			}
			required[field] = true
		}
		fmt.Fprintf(&body, "// %s is front matter decoded with the %s schema.\ntype %s struct {\n", name, name, name)
		used := map[string]bool{}
		for _, key := range sortedKeys(schema.Fields) {
			field := schema.Fields[key]
			fieldName := exportedFieldName(key)
			if !token.IsIdentifier(fieldName) || !token.IsExported(fieldName) || used[fieldName] {
				return nil, fmt.Errorf("content: invalid or colliding field %q in %s", key, name)
			}
			used[fieldName] = true
			typ, err := generatedFieldType(field)
			if err != nil {
				return nil, fmt.Errorf("content: %s.%s: %w", name, key, err)
			}
			usesTime = usesTime || strings.Contains(typ, "contenttime.Time")
			options := []string{}
			if field.Required || required[key] {
				options = append(options, "required")
			}
			if field.Reference != "" {
				if strings.Contains(field.Reference, ",") {
					return nil, fmt.Errorf("content: reference collection cannot contain commas")
				}
				options = append(options, "ref="+field.Reference)
			}
			tag := "json:" + strconv.Quote(key)
			if len(options) > 0 {
				tag += " content:" + strconv.Quote(strings.Join(options, ","))
			}
			fmt.Fprintf(&body, "\t%s %s %s\n", fieldName, typ, strconv.Quote(tag))
		}
		body.WriteString("}\n\n")
	}
	var source bytes.Buffer
	fmt.Fprintf(&source,
		"// Code generated by hyperchi/content.GenerateTypes; DO NOT EDIT.\n\npackage %s\n\n", packageName)
	if usesTime {
		source.WriteString("import contenttime \"time\"\n\n")
	}
	source.Write(body.Bytes())
	formatted, err := format.Source(source.Bytes())
	if err != nil {
		return nil, fmt.Errorf("content: format generated types: %w", err)
	}
	return formatted, nil
}

func generatedFieldType(field FieldDefinition) (string, error) {
	if err := validReferenceDefinition(field); err != nil {
		return "", err
	}
	if err := validElementDefinition(field); err != nil {
		return "", err
	}
	switch field.Type {
	case FieldTypeString:
		return "string", nil
	case FieldTypeInt:
		return "int", nil
	case FieldTypeFloat:
		return "float64", nil
	case FieldTypeBool:
		return "bool", nil
	case FieldTypeTime:
		return "contenttime.Time", nil
	case FieldTypeAny:
		return "any", nil
	case FieldTypeMap:
		return "map[string]any", nil
	case FieldTypeSlice:
		element := field.ElementType
		if field.Reference != "" {
			element = FieldTypeString
		}
		if element == "" {
			element = FieldTypeAny
		}
		switch element {
		case FieldTypeString, FieldTypeInt, FieldTypeFloat, FieldTypeBool, FieldTypeAny:
			typ, err := generatedFieldType(FieldDefinition{Type: element})
			return "[]" + typ, err
		default:
			return "", fmt.Errorf("unsupported slice element type %q", element)
		}
	default:
		return "", fmt.Errorf("unsupported field type %q", field.Type)
	}
}

func exportedFieldName(name string) string {
	var result strings.Builder
	parts := strings.FieldsFunc(name, func(r rune) bool { return r == '_' || r == '-' || r == '.' || unicode.IsSpace(r) })
	for _, part := range parts {
		switch strings.ToLower(part) {
		case "id", "url", "html", "http", "api", "json", "uuid":
			result.WriteString(strings.ToUpper(part))
		default:
			runes := []rune(part)
			runes[0] = unicode.ToUpper(runes[0])
			result.WriteString(string(runes))
		}
	}
	return result.String()
}
